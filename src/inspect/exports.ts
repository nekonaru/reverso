/** Report exports: SARIF for CI, CSV for spreadsheets and a self-contained HTML report. */
import type { AnalysisReport } from "../core/analyze-buffer.js";
import type { ScanReport } from "./scan.js";
import { VERSION } from "../version.js";

export function toSarif(report: AnalysisReport): unknown {
  const results: Array<Record<string, unknown>> = [];
  const location = { physicalLocation: { artifactLocation: { uri: report.file } } };

  for (const signal of report.packerSignals) {
    results.push({
      ruleId: "packer-signal",
      level: "warning",
      message: { text: signal },
      ...location,
    });
  }
  for (const check of report.hardening?.checks ?? []) {
    if (check.status !== "fail") continue;
    results.push({
      ruleId: `hardening-${check.name.toLowerCase().replace(/[^a-z0-9]+/g, "-")}`,
      level: "error",
      message: { text: `${check.name}: ${check.detail}` },
      ...location,
    });
  }
  for (const secret of report.javascript?.secrets ?? []) {
    results.push({
      ruleId: `secret-${secret.type}`,
      level: "warning",
      message: { text: `Possible ${secret.type} in JavaScript bundle at line ${secret.line}` },
      ...location,
    });
  }

  return {
    $schema: "https://json.schemastore.org/sarif-2.1.0.json",
    version: "2.1.0",
    runs: [{
      tool: {
        driver: {
          name: "Reverso",
          version: VERSION,
          informationUri: "https://github.com/nekonaru/reverso",
          rules: [
            { id: "packer-signal", shortDescription: { text: "Possible packed or encrypted content" } },
            { id: "hardening-check", shortDescription: { text: "Missing binary hardening feature" } },
            { id: "secret", shortDescription: { text: "Possible secret material" } },
          ],
        },
      },
      results,
    }],
  };
}

export function scanToCsv(report: ScanReport): string {
  const escape = (value: string | number): string => {
    const text = String(value);
    return /[",\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
  };
  const lines = ["file,format,sizeBytes,entropy,sha256,packerSignals"];
  for (const entry of report.entries) {
    lines.push([
      entry.file,
      entry.format,
      entry.sizeBytes,
      entry.entropy,
      entry.sha256,
      entry.packerSignals.join("; "),
    ].map(escape).join(","));
  }
  return lines.join("\n");
}

/** Builds a standalone HTML report with no external resources. */
export function toHtml(report: AnalysisReport): string {
  const data = JSON.stringify(report).replace(/<\/script/gi, "<\\/script");
  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>Reverso report: ${escapeHtml(report.file)}</title>
<style>
:root { color-scheme: dark; --ink:#101e26; --panel:#16242e; --line:#243644; --paper:#e9eef2; --muted:#a7b6c0; --gold:#f4c430; }
* { box-sizing:border-box; }
body { margin:0; background:var(--ink); color:var(--paper); font:16px/1.6 system-ui,"Segoe UI",sans-serif; }
main { max-width:900px; margin:0 auto; padding:2rem 1.25rem; }
h1 { font-size:1.8rem; margin:0 0 .25rem; }
h2 { margin-top:2rem; font-size:1.2rem; color:var(--gold); }
.cards { display:grid; grid-template-columns:repeat(auto-fit,minmax(180px,1fr)); gap:.75rem; margin-top:1.5rem; }
.card { background:var(--panel); border:1px solid var(--line); border-radius:12px; padding:1rem; }
.card span { display:block; color:var(--muted); font-size:.85rem; }
.card strong { font-size:1.1rem; }
code, pre { font-family:ui-monospace,Consolas,monospace; }
table { width:100%; border-collapse:collapse; }
th, td { text-align:left; border-bottom:1px solid var(--line); padding:.5rem; }
footer { color:var(--muted); font-size:.85rem; margin-top:3rem; border-top:1px solid var(--line); padding-top:1rem; }
</style>
</head>
<body>
<main>
<h1>Reverso report</h1>
<p id="file"></p>
<div class="cards" id="cards"></div>
<h2>Format</h2><pre id="format"></pre>
<h2>Hashes</h2><pre id="hashes"></pre>
<h2>Analysis</h2><div id="details"></div>
<footer>Generated by Reverso v${VERSION}. Static analysis only, nothing was executed.</footer>
</main>
<script type="application/json" id="report-data">${data}</script>
<script>
(function () {
  const report = JSON.parse(document.getElementById('report-data').textContent);
  const text = (id, value) => { const el = document.getElementById(id); if (el) el.textContent = value; };
  text('file', report.file);
  text('format', JSON.stringify(report.format, null, 2));
  text('hashes', JSON.stringify(report.hashes, null, 2));
  const cards = document.getElementById('cards');
  const entries = [
    ['Size', report.sizeBytes + ' bytes'],
    ['Entropy', report.entropy + ' bits/byte'],
    ['Strings', String(report.strings.total)],
    ['Packer signals', String(report.packerSignals.length)],
  ];
  for (const [label, value] of entries) {
    const card = document.createElement('div');
    card.className = 'card';
    const span = document.createElement('span');
    span.textContent = label;
    const strong = document.createElement('strong');
    strong.textContent = value;
    card.append(span, strong);
    cards.append(card);
  }
  const details = document.getElementById('details');
  const add = (title, rows) => {
    if (!rows.length) return;
    const h = document.createElement('h3');
    h.textContent = title;
    const table = document.createElement('table');
    for (const row of rows) {
      const tr = document.createElement('tr');
      for (const cell of row) {
        const td = document.createElement('td');
        td.textContent = String(cell);
        tr.append(td);
      }
      table.append(tr);
    }
    details.append(h, table);
  };
  add('Hardening', (report.hardening ? report.hardening.checks : []).map(c => [c.name, c.status, c.detail]));
  add('String categories', report.strings.categories.map(c => [c.category, c.count]));
  add('Packer signals', report.packerSignals.map(s => [s]));
})();
</script>
</body>
</html>
`;
}

function escapeHtml(value: string): string {
  return value.replace(/[&<>"']/g, (char) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
  })[char] ?? char);
}
